// ==================== FUNCTIONS ====================

// Function without parameters and return value

function greet() {
    console.log("Hello");
}

greet();


// Function with parameters and return value

function add(a, b) {
    return a + b;
}

console.log(add(1, 2));


// Function with parameters but without return value

function addNumbers(a, b) {
    console.log(a + b);
}

addNumbers(3, 6);
